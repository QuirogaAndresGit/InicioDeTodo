// Calcular el 15% de un número y el 1.5% de otro número.

const valor1 = parseInt(prompt("Digite el primer numero"))
const valor2 =parseInt(prompt("Digite el segundo numero"))

const reValor1 = valor1*0.15
const reValor2 = valor2*0.015

console.log(`El 15% calculado del primer numero es: ${reValor1}`);
console.log(`El 1.5% calculado del segundo numero es: ${reValor2}`);